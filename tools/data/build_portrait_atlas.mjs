#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { isUnavailableNbaHeadshot } from "./portrait_assets.mjs";

const root = resolve(new URL("../..", import.meta.url).pathname);
const sourceDirectory = resolve(process.argv[2] ?? join(root, "tools/data/portrait-source"));
const outputFile = resolve(process.argv[3] ?? join(root, "public/player-portraits/nba-atlas.webp"));
const idModule = resolve(process.argv[4] ?? join(root, "src/data/portraitAtlasIds.ts"));
const columns = 25;
const tileSize = 80;
if (!outputFile.endsWith(".webp")) throw new Error(`Atlas output must end in .webp: ${outputFile}`);

const candidateFiles = (await readdir(sourceDirectory, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && /^nba-\d+\.png$/u.test(entry.name))
  .map((entry) => entry.name)
  .sort((left, right) => Number(left.match(/\d+/u)?.[0]) - Number(right.match(/\d+/u)?.[0]));
const files = [];
for (const file of candidateFiles) {
  if (!isUnavailableNbaHeadshot(await readFile(join(sourceDirectory, file)))) files.push(file);
}

if (!files.length) throw new Error(`No NBA portrait PNGs found in ${sourceDirectory}`);

await mkdir(dirname(outputFile), { recursive: true });
const outputDirectory = dirname(outputFile);
const staleAtlasFiles = (await readdir(outputDirectory)).filter((name) => /^nba-atlas(?:-\d{3})?\.(?:jpg|webp)$/u.test(name));
await Promise.all(staleAtlasFiles.map((name) => rm(join(outputDirectory, name), { force: true })));
for (let row = 0; row < Math.ceil(files.length / columns); row += 1) {
  const rowFiles = files.slice(row * columns, (row + 1) * columns);
  const inputs = rowFiles.flatMap((file) => ["-i", join(sourceDirectory, file)]);
  const tiles = rowFiles.map((_, index) => `[${index}:v]scale=${tileSize}:${tileSize}:force_original_aspect_ratio=increase,crop=${tileSize}:${tileSize},format=rgba[tile${index}]`).join(";");
  const labels = rowFiles.map((_, index) => `[tile${index}]`).join("");
  const stack = rowFiles.length === 1 ? `${labels}pad=${columns * tileSize}:${tileSize}:0:0:black@0[out]` : `${labels}hstack=inputs=${rowFiles.length},pad=${columns * tileSize}:${tileSize}:0:0:black@0[out]`;
  const rowOutput = outputFile.replace(/\.webp$/u, `-${String(row).padStart(3, "0")}.webp`);
  execFileSync("ffmpeg", [
    "-y", ...inputs, "-filter_complex", `${tiles};${stack}`, "-map", "[out]",
    "-frames:v", "1", "-c:v", "libwebp", "-q:v", "85", rowOutput,
  ], { stdio: "ignore" });
}

await mkdir(dirname(idModule), { recursive: true });
await writeFile(
  idModule,
  `// Generated by tools/data/build_portrait_atlas.mjs. Do not edit manually.\nexport const PORTRAIT_ATLAS_PLAYER_IDS = ${JSON.stringify(files.map((file) => file.match(/\d+/u)?.[0]), null, 2)} as const;\nexport const PORTRAIT_ATLAS_STRIP_PATHS = ${JSON.stringify(Array.from({ length: Math.ceil(files.length / columns) }, (_, row) => `./player-portraits/nba-atlas-${String(row).padStart(3, "0")}.webp`), null, 2)} as const;\n`,
);
console.log(`Built ${files.length} portraits into ${Math.ceil(files.length / columns)} atlas strips beside ${outputFile}; skipped ${candidateFiles.length - files.length} NBA silhouette placeholders.`);
