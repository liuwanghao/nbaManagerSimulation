#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { mkdtemp, mkdir, readdir, rm, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";

const root = resolve(new URL("../..", import.meta.url).pathname);
const sourceDirectory = resolve(process.argv[2] ?? join(root, "tools/data/portrait-source"));
const outputFile = resolve(process.argv[3] ?? join(root, "public/player-portraits/nba-atlas.jpg"));
const idModule = resolve(process.argv[4] ?? join(root, "src/data/portraitAtlasIds.ts"));
const columns = 25;
const tileSize = 80;

const files = (await readdir(sourceDirectory, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && /^nba-\d+\.png$/u.test(entry.name))
  .map((entry) => entry.name)
  .sort((left, right) => Number(left.match(/\d+/u)?.[0]) - Number(right.match(/\d+/u)?.[0]));

if (!files.length) throw new Error(`No NBA portrait PNGs found in ${sourceDirectory}`);

const stagingDirectory = await mkdtemp(join(tmpdir(), "nba-portrait-atlas-"));
try {
  await mkdir(dirname(outputFile), { recursive: true });
  const outputDirectory = dirname(outputFile);
  const staleAtlasFiles = (await readdir(outputDirectory)).filter((name) => /^nba-atlas(?:-\d{3})?\.jpg$/u.test(name));
  await Promise.all(staleAtlasFiles.map((name) => rm(join(outputDirectory, name), { force: true })));
  for (let row = 0; row < Math.ceil(files.length / columns); row += 1) {
    const rowDirectory = join(stagingDirectory, String(row));
    await mkdir(rowDirectory);
    const rowFiles = files.slice(row * columns, (row + 1) * columns);
    await Promise.all(rowFiles.map((file, index) => symlink(join(sourceDirectory, file), join(rowDirectory, `${String(index).padStart(4, "0")}.png`))));
    const rowOutput = outputFile.replace(/\.jpg$/u, `-${String(row).padStart(3, "0")}.jpg`);
    execFileSync("ffmpeg", [
      "-y", "-framerate", "1", "-pattern_type", "glob", "-i", join(rowDirectory, "*.png"),
      "-vf", `scale=${tileSize}:${tileSize}:force_original_aspect_ratio=increase,crop=${tileSize}:${tileSize},tile=${columns}x1:padding=0:margin=0:nb_frames=${rowFiles.length}`,
      "-frames:v", "1", "-q:v", "2", rowOutput,
    ], { stdio: "ignore" });
  }
} finally {
  await rm(stagingDirectory, { recursive: true, force: true });
}

await mkdir(dirname(idModule), { recursive: true });
await writeFile(
  idModule,
  `// Generated by tools/data/build_portrait_atlas.mjs. Do not edit manually.\nexport const PORTRAIT_ATLAS_PLAYER_IDS = ${JSON.stringify(files.map((file) => file.match(/\d+/u)?.[0]), null, 2)} as const;\n`,
);
console.log(`Built ${files.length} portraits into ${Math.ceil(files.length / columns)} atlas strips beside ${outputFile}.`);
